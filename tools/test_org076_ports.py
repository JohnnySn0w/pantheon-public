NOW = the.NOW
WATCHMAN, RECOVERY = re_.RECOVERY_CANDIDATE, re_.RECOVERY_CANDIDATE


def _active(reader, persona, account):
    reader.units[(account, f"pantheon-persona-consume@{persona}.service")] = {
        "LoadState": "loaded", "ActiveState": "active", "Result": "success"}


def write_export(out: Path) -> None:
    """A real export for watchman and recovery, generated by health_export's OWN collect/sanitize/write code."""
    r = the._happy_reader("watchman", "codex-fallback", "watchman-pane:0")
    w = the._happy_reader("recovery", "claude-fallback", "recovery-pane:0")
    for attr in ("tails", "mtimes", "dirs", "units", "panes", "files"):
        getattr(r, attr).update(getattr(w, attr))
    _active(r, "watchman", "codex-fallback")
    _active(r, "recovery", "claude-fallback")
    rc = he.run([("watchman", "codex-fallback", "watchman-pane:0"), ("recovery", "claude-fallback", "recovery-pane:0")],
                reader=r, out_dir=out, now=NOW, hub=the.HUB)
    assert rc == 0


class Tmp(unittest.TestCase):
    def setUp(self):
        t = tempfile.TemporaryDirectory(prefix="org076-ports-")
        self.addCleanup(t.cleanup)
        self.dir = Path(t.name)

    def live(self, cand, now=NOW):
        return ports_mod.liveness_reason(cand, health_dir=self.dir, clock=lambda: now)

    def edit(self, persona, **changes):
        p = self.dir / f"{persona}.json"
        rec = json.loads(p.read_text())
        rec.update(changes)
        he.atomic_write_json(self.dir, f"{persona}.json", rec)


class Liveness(Tmp):
    def test_record_from_the_writers_own_code_is_live(self):
        write_export(self.dir)  # reader and writer cannot drift: the record is health_export's output
        rec = json.loads((self.dir / "watchman.json").read_text())
        self.assertEqual((rec["seat_state"], rec["expected_down"], rec["consume_unit"]), ("active", False, "active"))
        self.assertIn(rec["pane_state"], ports_mod.LIVE_PANE_STATES)
        self.assertEqual(self.live(WATCHMAN), (True, "live"))
        self.assertEqual(self.live(RECOVERY), (True, "live"))
        self.assertTrue(ports_mod.make_liveness(health_dir=self.dir, clock=lambda: NOW)(WATCHMAN))

    def test_each_not_live_state(self):
        for change, why in ((dict(pane_state="modal"), "pane_state=modal"),
                            (dict(pane_state="unknown"), "pane_state=unknown"),
                            (dict(consume_unit="failed"), "consume_unit=failed"),
                            (dict(seat_state="paused-intake"), "seat_state=paused-intake"),
                            (dict(seat_state="deep-sleep", expected_down=True), "expected_down")):
            with self.subTest(change=change):
                write_export(self.dir)
                self.edit("watchman", **change)
                self.assertEqual(self.live(WATCHMAN), (False, why))
                self.assertEqual(self.live(RECOVERY)[0], True, "another seat is judged on its own record")

    def test_stale_missing_or_invalid_signal_is_not_live(self):
        write_export(self.dir)
        self.assertEqual(self.live(WATCHMAN, NOW + rw.EXPORT_STALE_S + 1), (False, "export heartbeat stale"))
        self.assertEqual(self.live(WATCHMAN, NOW - rw.EXPORT_FUTURE_SKEW_S - 1),
                         (False, "export heartbeat in the future"))
        (self.dir / "watchman.json").unlink()
        self.assertEqual(self.live(WATCHMAN), (False, "no valid record"))
        (self.dir / he.HEARTBEAT_NAME).unlink()
        self.assertEqual(self.live(RECOVERY), (False, "export heartbeat missing or invalid"))

    def test_record_older_than_the_bound_with_fresh_heartbeat_is_not_live(self):
        write_export(self.dir)
        he.atomic_write_json(self.dir, he.HEARTBEAT_NAME,
                             {"schema_version": 1, "exported_at": NOW + 400, "persona_count": 2})
        self.assertEqual(self.live(WATCHMAN, NOW + 400), (False, "record stale"))

    def test_forged_symlink_garbage_and_oversize_records_are_not_live(self):
        for kind in ("symlink", "garbage", "oversize"):
            with self.subTest(kind=kind):
                write_export(self.dir)
                p = self.dir / "watchman.json"
                if kind == "symlink":
                    real = self.dir / "elsewhere"
                    real.write_text(p.read_text())
                    p.unlink()
                    p.symlink_to(real)
                elif kind == "garbage":
                    p.write_text("{not json")
                else:
                    p.write_text(json.dumps({"x": "a" * 20000}))
                self.assertEqual(self.live(WATCHMAN)[0], False)

    def test_lookup_is_by_name_only_never_by_account(self):
        write_export(self.dir)
        zzz = re_.Candidate("zzz", "claude", "claude-fallback")  # Recovery's account, not Recovery's persona
        self.assertEqual(self.live(zzz), (False, "no valid record"))
        self.assertTrue(self.live(RECOVERY)[0])

    def test_unreadable_dir_and_raising_reader_never_raise(self):
        self.assertEqual(ports_mod.liveness_reason(WATCHMAN, health_dir=self.dir / "nope", clock=lambda: NOW)[0], False)
        write_export(self.dir)
        with mock.patch.object(rw, "load_health", side_effect=OSError("boom")):
            live = ports_mod.make_liveness(health_dir=self.dir, clock=lambda: NOW)
            self.assertIs(live(WATCHMAN), False)

    def test_prod_default_dir_is_the_health_export(self):
        self.assertEqual(rw.DEFAULT_HEALTH_DIR, Path("/run/pantheon-health"))


class Transport:
    """Records what would be delivered at the lowest seam (inbox_consumer's orchestrator-mailbox leg)."""
    def __init__(self, ok=True):
        self.sent, self.telegram, self.ok = [], [], ok

    def deliver(self, msg, vocab):
        self.sent.append((msg, vocab))
        return self.ok

    def tg(self, text):
        self.telegram.append(text)
        return True


