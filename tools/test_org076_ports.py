class RepeatedPageOverCycles(base.Rig):
    """The same page condition over 3 run_cycles delivers once (the runner's _page_once dedupe)."""
    def test_dirty_clone_page_delivered_once_over_three_cycles(self):
        t = Transport()
        with mock.patch.object(ic, "_deliver_recovery_self_alert_to_orchestrator", t.deliver), \
                mock.patch.object(ic, "_send_telegram_alert", t.tg), \
                mock.patch.object(ic, "_persona_is_muted", lambda a: False):
            (self.fx.repo / "stray.txt").write_text("x")
            for _ in range(3):
                rep = run.run_cycle(self.cfg, self.ports(page=ports_mod.make_page(), liveness=lambda c: True))
                self.assertEqual(rep.exit_code, run.EXIT_REFUSED)
        self.assertEqual(len(t.sent), 1)
        self.assertIn("dedicated clone not clean", t.sent[0][0])
        self.assertEqual(t.telegram, [])


