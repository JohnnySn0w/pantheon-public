"""Render the ORG-068 coverage matrix from the ORG-081 registry (ORG-081 §5).

Deterministic: rows in registry order, columns in ORG-068 order, no timestamps.
The rendered file is committed (``registry/system-coverage.md``) and CI runs
``--check`` so the yaml and the markdown cannot drift.
"""

from __future__ import annotations

from typing import Any, Mapping

from tools.germinate.registry import schema as S

RENDERED_REL = "registry/system-coverage.md"

GLYPHS = {
    S.STATUS_COVERED: "✓",
    S.STATUS_PARTIAL: "◐",
    S.STATUS_MISSING: "✗",
    S.STATUS_PARTIAL_BY_DESIGN: "◑",
    S.STATUS_NOT_APPLICABLE: "n/a",
}
UNRECORDED = "—"
LEGACY_MARK = "ᴸ"
LEG_HEADERS = ("Install", "Configure", "Health-mon", "Update", "Remove")

HEADER = """<!-- GENERATED by `python3 -m tools.germinate registry render` from registry/systems.yaml.
     Do not edit by hand: edit the registry and re-render (CI runs `render --check`). -->

# System lifecycle coverage (rendered from the ORG-081 registry)

Legend: ✓ covered · ◐ partial · ✗ missing · ◑ partial_by_design · n/a not_applicable ·
— not recorded. A {legacy} suffix means the cell is `legacy_coverage` (prior art on a
`not_adopted` component, never a claim of contract adoption, ORG-081 §3).
""".format(legacy=LEGACY_MARK)


def _escape(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _cell(row: Mapping, leg: str) -> str:
    for block, suffix in (("legs", ""), ("legacy_coverage", LEGACY_MARK)):
        cells = row.get(block)
        if isinstance(cells, dict) and isinstance(cells.get(leg), dict):
            status = cells[leg].get("status")
            return GLYPHS.get(status, "?") + suffix
    return UNRECORDED


def _crossref(row: Mapping) -> str:
    parts = [f"`{row.get('contract_adoption', '?')}`"]
    adrs = row.get("adr")
    if isinstance(adrs, list) and adrs:
        parts.append(", ".join(str(a) for a in adrs))
    if row.get("note"):
        parts.append(_escape(row["note"]))
    return "; ".join(parts)


def render_matrix(doc: Mapping[str, Any]) -> str:
    rows = [r for r in doc.get("systems") or [] if isinstance(r, dict)]
    lines = [HEADER, "## Components", ""]
    lines.append("| Major system | Steward | " + " | ".join(LEG_HEADERS) + " | Realization / cross-ref |")
    lines.append("|---" * (len(LEG_HEADERS) + 3) + "|")
    for row in rows:
        if row.get("kind") != S.KIND_COMPONENT:
            continue
        name = f"{_escape(row.get('title', row.get('id', '?')))} (`{row.get('id', '?')}`)"
        cells = [_cell(row, leg) for leg in S.LEGS]
        lines.append(
            f"| {name} | {_escape(row.get('steward', '?'))} | " + " | ".join(cells) + f" | {_crossref(row)} |"
        )
    planes = [r for r in rows if r.get("kind") == S.KIND_EXTERNAL_PLANE]
    if planes:
        lines += ["", "## External planes (legibility only, not engine-executed, ORG-081 D-5)", ""]
        lines.append("| Plane | Steward | Relationship | Tracking | ADRs |")
        lines.append("|---|---|---|---|---|")
        for row in planes:
            tracking = row.get("tracking") if isinstance(row.get("tracking"), dict) else {}
            track = ", ".join(f"{k}: {v}" for k, v in tracking.items())
            adrs = ", ".join(str(a) for a in row.get("adr") or [])
            lines.append(
                f"| {_escape(row.get('title', '?'))} (`{row.get('id', '?')}`) | {_escape(row.get('steward', '?'))} | "
                f"{_escape(row.get('relationship', ''))} | {track} | {adrs} |"
            )
    return "\n".join(lines) + "\n"


def render_show(doc: Mapping[str, Any]) -> str:
    """Compact one-line-per-row listing for `germinate registry show`."""
    out = []
    for row in doc.get("systems") or []:
        if not isinstance(row, dict):
            continue
        if row.get("kind") == S.KIND_COMPONENT:
            legs = " ".join(f"{leg}={_cell(row, leg)}" for leg in S.LEGS)
            out.append(f"{row.get('id')}\tcomponent\t{row.get('contract_adoption')}\t{row.get('steward')}\t{legs}")
        else:
            out.append(f"{row.get('id')}\t{row.get('kind')}\t-\t{row.get('steward')}\t-")
    return "\n".join(out) + ("\n" if out else "")
