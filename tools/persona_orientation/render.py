class HermesSopTarget(SopRenderTarget):
    harness = "hermes"
    in_all = False  # opt-in: `--harness all` stays claude+codex (plan §2.5 gap 1)

    def skill_root(self, ctx: RenderContext) -> Path:
        return ctx.hermes_skills_root

    def skill_relpath(self, slug: str) -> Path:
        return Path(HERMES_SKILL_CATEGORY) / (SOP_SKILL_PREFIX + slug) / "SKILL.md"

    def orphan_scan_dir(self, ctx: RenderContext) -> Path:
        return self.skill_root(ctx) / HERMES_SKILL_CATEGORY

    def bindings_path(self, root: Path, ctx: RenderContext) -> Path:
        return ctx.home / HERMES_BINDINGS_RELDIR / Path(SOP_SKILL_BINDINGS).name


#: harness -> target, in `--harness all` order for the in_all ones.
RENDER_TARGETS: dict[str, SopRenderTarget] = {
    target.harness: target for target in (ClaudeSopTarget(), CodexSopTarget(), HermesSopTarget())
}


def _unwritable_hermes_root(harnesses: tuple[str, ...], ctx: RenderContext) -> Path | None:
    """T-5011 PR-D (PR-C LOW): in write mode, the hermes skill root (or its
    nearest existing ancestor, which mkdir would write into) must be writable,
    else the run stops before writing anything. None when hermes is not selected."""
    if "hermes" not in harnesses:
        return None
    root = RENDER_TARGETS["hermes"].skill_root(ctx)
    probe = root
    while not probe.exists() and probe.parent != probe:
        probe = probe.parent
    return None if os.access(probe, os.W_OK) else root


def entry_selects(entry: dict, harness: str) -> bool:
    """An entry without `harnesses:` renders for every harness (the pre-T-5011 shape)."""
    selected = entry.get("harnesses")
    return selected is None or harness in selected


def resolve_seat_roles() -> tuple[frozenset[str] | None, str]:
    """T-5214: (functional role ids of the seat running this render, description).

    Identity is the running OS account -> persona (agent_role_map.account_persona) ->
    functional_roles (heads imply their regular role). Anything unresolvable returns
    (None, why): the caller FAILS OPEN and renders everything, so an unknown identity
    never drops a skill. Deliberate consequence: the hermes root render runs as root,
    which is not a fleet account, so it fails open and is not role-scoped."""
    try:
        tools_dir = str(Path(__file__).resolve().parents[1])
        if tools_dir not in sys.path:
            sys.path.insert(0, tools_dir)
        import agent_role_map

        account = getpass.getuser()
        persona = agent_role_map.account_persona(account)
        if persona is None:
            return None, f"account {account!r} is not a fleet account"
        roles = agent_role_map.functional_roles(persona)
        if not roles:
            return None, f"persona {persona!r} holds no functional roles"
        return roles, f"persona {persona!r} (account {account!r})"
    except Exception as exc:  # fail open on ANY identity-source problem
        return None, f"identity lookup failed: {type(exc).__name__}: {exc}"


def entry_in_scope(entry: dict, seat_roles: frozenset[str] | None) -> bool:
    """No `roles:` on the entry, or unknown seat identity (None): in scope (today's behavior)."""
    wanted = entry.get("roles")
    return wanted is None or seat_roles is None or bool(seat_roles & set(wanted))


def render_sop_skill(cache: SourceCache, entry: dict, harness: str) -> str:
    if harness not in RENDER_TARGETS:
        raise ValueError(f"unknown harness {harness!r}")
    frontmatter = RENDER_TARGETS[harness].frontmatter
    sop = entry["sop"]
    text = strip_front_matter(cache.text(sop))
    spec = entry.get("body") or {"extract": "full-file"}
    if spec["extract"] == "full-file":
        scope = f"> Source of truth: `{sop}` (pantheon-config). This skill is a rendered copy: edit the SOP, not this file."
        body = extract_full_file(text)
        footer: list[str] = []
    else:
        headings = spec["headings"]
        scope = (
            f"> Excerpt of `{sop}` (pantheon-config), sections: "
            + "; ".join(f"`{h}`" for h in headings)
            + ". This skill is a rendered copy: edit the SOP, not this file."
        )
        body = "\n\n".join(_sop_heading_region(text, h) for h in headings)
        footer = ["", f"Full SOP: `{sop}`."]
    scope += f" Relative links below resolve against `{sop.rsplit('/', 1)[0]}/` in the pantheon-config repo."
    header = (
        f"{GENERATED_MARKER} from {SOP_SKILLS_MANIFEST} + {sop}. "
        "Do not hand-edit; edit the SOP (or its manifest entry) and re-render. -->"
    )
    parts = [_frontmatter_text(frontmatter(entry)), "", header, "", scope, "", body, *footer]
    return "\n".join(parts).rstrip("\n") + "\n"


def render_sop_skills(root: Path, harnesses: tuple[str, ...] = HARNESSES) -> tuple[dict[str, str], dict[str, dict]]:
    """Returns (artifacts, source_bindings); artifact keys are "sop:<slug>:<harness>".
    Pending hooks render nothing and stamp nothing."""
    manifest = load_sop_skills_manifest(root)
    cache = SourceCache(root)
    artifacts = {
        f"sop:{entry['slug']}:{harness}": render_sop_skill(cache, entry, harness)
        for entry in manifest["skills"]
        for harness in harnesses
        if entry_selects(entry, harness)
    }
    return artifacts, cache.bindings


def default_codex_home(home: Path) -> Path:
    env = os.environ.get("CODEX_HOME")
    return Path(env) if env else home / ".codex"


def sop_output_paths(
    home: Path, codex_home: Path, artifacts: dict[str, str], *, hermes_skills_root: Path | None = None
) -> dict[str, Path]:
    ctx = RenderContext(home, codex_home, hermes_skills_root)
    paths: dict[str, Path] = {}
    for key in artifacts:
        _, slug, harness = key.split(":")
        target = RENDER_TARGETS[harness]
        paths[key] = target.skill_root(ctx) / target.skill_relpath(slug)
    return paths


def _unnamed_prefixed(prefix: str, active: set[str], skills_dirs: list[Path]) -> list[Path]:
    """`prefix`-named entries in the given skills dirs whose name is not in `active`."""
    entries: list[Path] = []
    for base in skills_dirs:
        if base.is_dir():
            entries += [c for c in sorted(base.iterdir()) if c.name.startswith(prefix) and c.name not in active]
    return entries


def _unnamed_sop_entries(
    root: Path, home: Path, codex_home: Path, harnesses: tuple[str, ...], hermes_skills_root: Path | None = None,
    seat_roles: frozenset[str] | None = None,
) -> list[Path]:
    """pantheon-sop-* entries in the harnesses' skills dirs that the manifest does not
    name FOR THAT HARNESS (an entry whose `harnesses:` omits it is not active there), or
    that `roles:` excludes for this seat (T-5214)."""
    skills = load_sop_skills_manifest(root)["skills"]
    ctx = RenderContext(home, codex_home, hermes_skills_root)
    entries: list[Path] = []
    for harness in harnesses:
        active = {SOP_SKILL_PREFIX + e["slug"] for e in skills if entry_selects(e, harness) and entry_in_scope(e, seat_roles)}
        entries += _unnamed_prefixed(SOP_SKILL_PREFIX, active, [RENDER_TARGETS[harness].orphan_scan_dir(ctx)])
    return entries


def _is_link(entry: Path) -> bool:
    return entry.is_symlink() or (entry / "SKILL.md").is_symlink()


def _generated_only(entries: list[Path]) -> list[Path]:
    """The entries that are ours to delete: not a link, and a real SKILL.md carrying GENERATED_MARKER."""
    return [
        entry for entry in entries
        if not _is_link(entry)
        and (entry / "SKILL.md").is_file()
        and GENERATED_MARKER in (entry / "SKILL.md").read_text(encoding="utf-8")
    ]


def find_sop_orphans(
    root: Path, home: Path, codex_home: Path, harnesses: tuple[str, ...], hermes_skills_root: Path | None = None,
    seat_roles: frozenset[str] | None = None,
) -> list[Path]:
    """Generated pantheon-sop-* skill dirs the manifest no longer names. Only a
    SKILL.md carrying our GENERATED marker counts, so hand-written skills and
    every other prefix are never candidates here (pantheon-role-* orphans are
    find_role_orphans', claude harness only). A symlinked
    dir, or a dir whose SKILL.md is a symlink, is never a candidate either:
    deleting through it would remove a file outside the skills dir (a seat's
    ~/.claude/skills really holds links into claude-config/skills/)."""
    return _generated_only(_unnamed_sop_entries(root, home, codex_home, harnesses, hermes_skills_root, seat_roles))


def find_sop_links(
    root: Path, home: Path, codex_home: Path, harnesses: tuple[str, ...], hermes_skills_root: Path | None = None,
    seat_roles: frozenset[str] | None = None,
) -> list[Path]:
    """The symlinked pantheon-sop-* entries find_sop_orphans skips (reported, never touched)."""
    return [e for e in _unnamed_sop_entries(root, home, codex_home, harnesses, hermes_skills_root, seat_roles) if _is_link(e)]


ROLE_SKILL_PREFIX = "pantheon-role-"


def _unnamed_role_entries(root: Path, home: Path) -> list[Path]:
    """pantheon-role-* entries in the CLAUDE skills dir whose role the persona manifest does not
    name. Active = every manifest role, rendered or not (a named-but-unrendered role, e.g. a
    Consultant role, is never a guess to delete). Claude harness only: nothing renders role skills
    into the codex skills dir, so a generated one there is not provably ours (T-4557)."""
    active = {ROLE_SKILL_PREFIX + r["id"].replace("_", "-") for r in load_manifest(root)["roles"]}
    return _unnamed_prefixed(ROLE_SKILL_PREFIX, active, [home / ".claude" / "skills"])


def find_role_orphans(root: Path, home: Path) -> list[Path]:
    """Generated pantheon-role-* skill dirs (claude harness only) the persona manifest no
    longer names. Same safety rules as find_sop_orphans: only a real SKILL.md carrying the
    GENERATED marker; symlinked dirs/SKILL.md and hand-written skills are never candidates."""
    return _generated_only(_unnamed_role_entries(root, home))


def find_role_links(root: Path, home: Path) -> list[Path]:
    """The symlinked pantheon-role-* entries find_role_orphans skips (reported, never touched)."""
    return [e for e in _unnamed_role_entries(root, home) if _is_link(e)]


def linked_outputs(paths: dict[str, Path]) -> dict[str, Path]:
    """T-4488: the write-path twin of the prune guard. The rendered outputs (key -> the
    symlinked component) whose skill dir or SKILL.md is a symlink: writing through one
    would overwrite a file outside the skills dir, so every mode skips them."""
    linked: dict[str, Path] = {}
    for key, path in paths.items():
        if path.parent.is_symlink():
            linked[key] = path.parent
        elif path.is_symlink():
            linked[key] = path
    return linked


def _note_linked_outputs(prefix: str, linked: dict[str, Path]) -> None:
    if linked:
        print(f"NOTE -- symlinked {prefix}* outputs are not ours, skipped (never written):")
        for link in linked.values():
            print(f"  {link}")


def prune_orphan(orphan: Path) -> None:
    (orphan / "SKILL.md").unlink()
    try:
        orphan.rmdir()
    except OSError:
        pass  # someone keeps other files there: leave them


def write_sop_skill_bindings(root: Path, bindings: dict[str, dict], path: Path | None = None) -> None:
    """Stamp ``bindings`` into ``path`` (default: the repo's SOP_SKILL_BINDINGS).
    T-5011 PR-C: a target whose bindings are seat-local (hermes) passes its own."""
    path = path if path is not None else root / SOP_SKILL_BINDINGS
    header = (
        "# WRITE-ONLY by tools/persona_orientation/render.py. Do not hand-edit.\n"
        "# SOP-skill stamps ({source_path: {git_sha, git_blob, sha256, byte_length}}) as of\n"
        "# the most recent non-dry-run render of tools/persona_orientation/sop-skills.yaml.\n"
        "# Read by tools/persona_orientation/check_stale.py and the real-repo gate in\n"
        "# tools/test_persona_orientation_sop_skills.py. Same record format as\n"
        "# rulebook/persona-orientation/source-bindings.yaml, kept separate because the\n"
        "# manifest lives outside the guarded rulebook tree.\n"
    )
    # T-4669: keep an existing stamp whose content is unchanged. git_sha is provenance only
    # here (see test_persona_orientation_sop_skills.sop_stamp_problems): after a squash merge
    # the committed git_sha is the PR branch's commit, while `git log -1 -- <sop>` on main
    # names the squash commit. Re-stamping that difference dirtied every seat clone the
    # post-merge re-render ran in (2026-10-06: recovery/specialist/archivist/codex; codex then could
    # not ff-pull). A real SOP edit changes git_blob, so it is still re-stamped.
    try:
        existing = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError):
        existing = {}
    content_keys = ("git_blob", "sha256", "byte_length")
    merged = {}
    for rel_path, stamp in bindings.items():
        old = existing.get(rel_path) if isinstance(existing, dict) else None
        same = isinstance(old, dict) and all(old.get(k) == stamp.get(k) for k in content_keys)
        merged[rel_path] = old if same else stamp
    ordered = {k: merged[k] for k in sorted(merged)}
    body = yaml.safe_dump(ordered, sort_keys=True, default_flow_style=False) if ordered else "{}\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header + body, encoding="utf-8")


def run_sop_skills(root: Path, home: Path, mode: str, harnesses: tuple[str, ...] = ("claude",),
                   codex_home: Path | None = None, hermes_skills_root: Path | None = None,
                   stamp: bool = True, seat_roles: frozenset[str] | None = None) -> int:
    """seat_roles=None means identity unknown: fail open, render everything (T-5214)."""
    if not (root / SOP_SKILLS_MANIFEST).exists():
        return 0
    codex_home = codex_home if codex_home is not None else default_codex_home(home)
    artifacts, bindings = render_sop_skills(root, harnesses)  # bindings stay full: stamps never move
    out_of_scope = {
        e["slug"] for e in load_sop_skills_manifest(root)["skills"] if not entry_in_scope(e, seat_roles)
    }
    artifacts = {k: v for k, v in artifacts.items() if k.split(":")[1] not in out_of_scope}
    paths = sop_output_paths(home, codex_home, artifacts, hermes_skills_root=hermes_skills_root)
    orphans = find_sop_orphans(root, home, codex_home, harnesses, hermes_skills_root, seat_roles)
    links = find_sop_links(root, home, codex_home, harnesses, hermes_skills_root, seat_roles)
    pending = load_sop_skills_manifest(root)["pending"]
    if links:
        print("NOTE -- symlinked pantheon-sop-* entries are not ours, skipped (never pruned):")
        for link in links:
            print(f"  {link}")
    linked = linked_outputs(paths)
    _note_linked_outputs(SOP_SKILL_PREFIX, linked)

    if mode == "dry-run":
        for key, text in artifacts.items():
            print(f"===== {paths[key]} =====")
            print(text)
        for orphan in orphans:
            print(f"(would prune orphan {orphan})")
        print(f"({len(pending)} pending SOP-skill hook(s) not rendered)")
        return 0

    if mode == "check":
        stale = [
            str(paths[key])
            for key, text in artifacts.items()
            if key not in linked
            and (not paths[key].exists() or paths[key].read_text(encoding="utf-8") != text)
        ]
        if stale:
            print("STALE -- the following SOP-skill artifacts do not match a fresh render:", file=sys.stderr)
            for item in stale:
                print(f"  {item}", file=sys.stderr)
        if orphans:
            print("ORPHAN -- generated SOP-skill dirs the manifest no longer names "
                  "(render.py without --check prunes them):", file=sys.stderr)
            for orphan in orphans:
                print(f"  {orphan}", file=sys.stderr)
        if stale or orphans:
            return 2
        print("OK -- all rendered SOP-skill artifacts match on-disk content.")
        return 0

    ctx = RenderContext(home, codex_home, hermes_skills_root)
    unwritable = _unwritable_hermes_root(harnesses, ctx)
    if unwritable is not None:
        print(
            f"ERROR -- the hermes skills root {unwritable} is not writable by this account; "
            "the hermes SOP skills are a root render step: pass --hermes-skills-root "
            "<the pinned dir under /opt/pantheon/hermes-skills> as its owner (nothing was written).",
            file=sys.stderr,
        )
        return 1
    for key, text in artifacts.items():
        if key in linked:
            continue
        paths[key].parent.mkdir(parents=True, exist_ok=True)
        paths[key].write_text(text, encoding="utf-8")
    # T-5011 PR-C: each selected target's bindings path, once (claude/codex share the repo's).
    # T-3434: --no-stamp (stamp=False) leaves every bindings file untouched.
    if stamp:
        for bindings_path in dict.fromkeys(RENDER_TARGETS[h].bindings_path(root, ctx) for h in harnesses):
            write_sop_skill_bindings(root, bindings, bindings_path)
    for orphan in orphans:
        prune_orphan(orphan)
    print(
        f"Rendered {len(artifacts) - len(linked)} SOP-skill artifact(s) ({len(linked)} symlinked, skipped); stamped {len(bindings) if stamp else 0} source binding(s); "
        f"pruned {len(orphans)} orphan(s); {len(pending)} pending hook(s) not rendered; "
        f"{len(out_of_scope)} skill(s) role-excluded for this seat."
    )
    return 0


def run_persona(root: Path, home: Path, mode: str, stamp: bool = True) -> int:
    artifacts, bindings = render_all(root)
    paths = output_paths(home, artifacts)
    orphans = find_role_orphans(root, home)
    links = find_role_links(root, home)
    if links:
        print("NOTE -- symlinked pantheon-role-* entries are not ours, skipped (never pruned):")
        for link in links:
            print(f"  {link}")
    linked = linked_outputs(paths)
    _note_linked_outputs("pantheon-", linked)

    if mode == "dry-run":
        for key, text in artifacts.items():
            print(f"===== {paths[key]} =====")
            print(text)
        for orphan in orphans:
            print(f"(would prune orphan {orphan})")
        return 0

    if mode == "check":
        mismatches = [
            str(paths[key])
            for key, text in artifacts.items()
            if key not in linked
            and (not paths[key].exists() or paths[key].read_text(encoding="utf-8") != text)
        ]
        if mismatches:
            print("STALE -- the following artifacts do not match a fresh render:", file=sys.stderr)
            for m in mismatches:
                print(f"  {m}", file=sys.stderr)
        if orphans:
            print("ORPHAN -- generated role-skill dirs the manifest no longer names "
                  "(render.py without --check prunes them):", file=sys.stderr)
            for orphan in orphans:
                print(f"  {orphan}", file=sys.stderr)
        if mismatches or orphans:
            return 2
        print("OK -- all rendered artifacts match on-disk content.")
        return 0

    # default: write
    for key, text in artifacts.items():
        if key in linked:
            continue
        path = paths[key]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    if stamp:  # T-3434: --no-stamp never touches the committed bindings file
        write_source_bindings(root, bindings)
    for orphan in orphans:
        prune_orphan(orphan)
    print(
        f"Rendered {len(artifacts) - len(linked)} artifact(s) ({len(linked)} symlinked, skipped); stamped {len(bindings) if stamp else 0} source binding(s); "
        f"pruned {len(orphans)} orphan role skill(s)."
    )
    return 0


