def render_all(root: Path) -> tuple[dict[str, str], dict[str, dict]]:
    """Returns (artifacts, source_bindings). `artifacts` maps an internal key
    ("base" or "role:<id>") to rendered text; resolve to actual output paths
    via output_paths()."""
    manifest = load_manifest(root)
    role_deltas = load_role_deltas(root)
    cache = SourceCache(root)

    artifacts: dict[str, str] = {"base": render_base_skill(cache, manifest)}
    for role in manifest["roles"]:
        if role["id"] not in CLAUDE_ROLES:
            continue
        artifacts[f"role:{role['id']}"] = render_role_skill(cache, role, role_deltas)

    return artifacts, cache.bindings


def output_paths(home: Path, artifacts: dict[str, str]) -> dict[str, Path]:
    paths: dict[str, Path] = {}
    for key in artifacts:
        if key == "base":
            paths[key] = home / ".claude" / "skills" / "pantheon-persona-orientation" / "SKILL.md"
        else:
            role_id = key.split(":", 1)[1]
            skill_name = f"pantheon-role-{role_id.replace('_', '-')}"
            paths[key] = home / ".claude" / "skills" / skill_name / "SKILL.md"
    return paths


def write_source_bindings(root: Path, bindings: dict[str, dict]) -> None:
    path = root / "rulebook" / "persona-orientation" / "source-bindings.yaml"
    header = (
        "# WRITE-ONLY by tools/persona_orientation/render.py. Do not hand-edit.\n"
        "# Records {source_path: {git_sha, git_blob, sha256, byte_length}} as of\n"
        "# the most recent non-dry-run render. Read by\n"
        "# tools/persona_orientation/check_stale.py to detect drift.\n"
    )
    # T-4726: keep an existing stamp whose content is unchanged, as T-4669 does for the
    # SOP-skill stamps. git_sha is provenance only (the gate checks the blob): after a
    # squash merge the committed git_sha is the PR branch's commit, and re-stamping it to
    # the squash commit would leave a tracked edit in every seat clone that re-renders.
    # A real source edit changes git_blob, so it is still re-stamped.
    try:
        existing = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError):
        existing = {}
    content_keys = ("git_blob", "sha256", "byte_length")
    merged = {}
    for rel_path, stamp in bindings.items():
        old = existing.get(rel_path) if isinstance(existing, dict) else None
        same = isinstance(old, dict) and all(old.get(k) == stamp.get(k) for k in content_keys)
        merged[rel_path] = old if same else stamp
    ordered = {k: merged[k] for k in sorted(merged)}
    body = yaml.safe_dump(ordered, sort_keys=True, default_flow_style=False)
    path.write_text(header + body, encoding="utf-8")


