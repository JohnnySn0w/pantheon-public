SOP_SKILLS_MANIFEST = "tools/persona_orientation/sop-skills.yaml"
SOP_SKILL_BINDINGS = "tools/persona_orientation/sop-skill-bindings.yaml"
SOP_SKILL_PREFIX = "pantheon-sop-"
SOP_DIRS = ("sop/standard/", "sop/remediation/")  # T-4782: remediation SOPs render too
HARNESSES = ("claude", "codex")  # the `--harness all` set: RENDER_TARGETS with in_all (test-pinned)
GENERATED_MARKER = "<!-- GENERATED by tools/persona_orientation/render.py"


_SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
_MAX_SKILL_NAME = 64
_MAX_DESCRIPTION = 1024
_BODY_EXTRACTS = ("full-file", "heading-region")
_FRONT_MATTER_RE = re.compile(r"\A---\n.*?\n---\n", re.DOTALL)


def _single_line(value: Any, label: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{label} must be a non-empty string")
    if "\n" in value or "\r" in value:
        raise ValueError(f"{label} must be a single line")
    return value


def _check_slug(slug: Any, seen: set[str]) -> str:
    if not isinstance(slug, str) or not _SLUG_RE.match(slug):
        raise ValueError(f"slug {slug!r} must be lowercase words joined by single hyphens")
    if len(SOP_SKILL_PREFIX + slug) > _MAX_SKILL_NAME:
        raise ValueError(f"skill name {SOP_SKILL_PREFIX + slug!r} exceeds {_MAX_SKILL_NAME} characters")
    if slug in seen:
        raise ValueError(f"duplicate slug {slug!r} (slugs are unique across skills and pending)")
    seen.add(slug)
    return slug


def _check_sop_path(root: Path, sop: Any, *, must_exist: bool) -> str:
    if not isinstance(sop, str) or not sop.startswith(SOP_DIRS) or not sop.endswith(".md"):
        raise ValueError(f"sop {sop!r} must be a sop/standard/*.md or sop/remediation/*.md path")
    if ".." in Path(sop).parts:
        raise ValueError(f"sop {sop!r} must not contain '..'")
    if must_exist and not (root / sop).is_file():
        raise ValueError(f"sop {sop!r} does not exist")
    return sop


def _check_skill_entry(root: Path, entry: Any, seen: set[str]) -> dict:
    if not isinstance(entry, dict):
        raise ValueError(f"skills entry must be a mapping, got {entry!r}")
    slug = _check_slug(entry.get("slug"), seen)
    if "harnesses" in entry:
        # T-5011 PR-C (plan §2.5 gap 3, artisan ruling 4): an optional selection.
        # Absent: the entry renders for every harness, as before.
        selected = entry["harnesses"]
        if (
            not isinstance(selected, list)
            or not selected
            or not all(isinstance(h, str) and h in RENDER_TARGETS for h in selected)
            or len(set(selected)) != len(selected)
        ):
            raise ValueError(
                f"{slug}: harnesses must be a non-empty list of distinct names from {sorted(RENDER_TARGETS)}"
            )
    if "roles" in entry:
        # T-5214: optional seat-role scoping. Absent: every seat renders it.
        roles = entry["roles"]
        if (
            not isinstance(roles, list)
            or not roles
            or not all(isinstance(r, str) and r.strip() for r in roles)
            or len(set(roles)) != len(roles)
        ):
            raise ValueError(f"{slug}: roles must be a non-empty list of distinct role ids")
    _check_sop_path(root, entry.get("sop"), must_exist=True)
    description = _single_line(entry.get("description"), f"{slug}: description")
    if len(description) > _MAX_DESCRIPTION:
        raise ValueError(f"{slug}: description exceeds {_MAX_DESCRIPTION} characters")
    if entry.get("short_description") is not None:
        _single_line(entry["short_description"], f"{slug}: short_description")
    body = entry.get("body") or {"extract": "full-file"}
    if body.get("extract") not in _BODY_EXTRACTS:
        raise ValueError(f"{slug}: body.extract must be one of {_BODY_EXTRACTS}")
    if body["extract"] == "heading-region":
        headings = body.get("headings")
        if not isinstance(headings, list) or not headings or not all(isinstance(h, str) for h in headings):
            raise ValueError(f"{slug}: heading-region needs a non-empty headings list")
    return entry


def _check_pending_entry(root: Path, entry: Any, seen: set[str]) -> dict:
    if not isinstance(entry, dict):
        raise ValueError(f"pending entry must be a mapping, got {entry!r}")
    _check_slug(entry.get("slug"), seen)
    _single_line(entry.get("awaiting"), f"{entry['slug']}: awaiting")
    if "harnesses" in entry:
        # T-5011 PR-D (PR-C LOW): a pending hook renders nothing, so a selection
        # on it would be silently ignored; declare it when the entry moves to skills.
        raise ValueError(f"{entry['slug']}: harnesses: belongs on a skills entry, not a pending one")
    if "roles" in entry:
        raise ValueError(f"{entry['slug']}: roles: belongs on a skills entry, not a pending one")
    if entry.get("sop") is not None:  # a hint; the SOP may not exist yet
        _check_sop_path(root, entry["sop"], must_exist=False)
    return entry


def load_sop_skills_manifest(root: Path) -> dict:
    """{"skills": [...], "pending": [...]}; raises ValueError on a malformed entry."""
    with open(root / SOP_SKILLS_MANIFEST, encoding="utf-8") as f:
        raw = yaml.safe_load(f) or {}
    seen: set[str] = set()
    skills = [_check_skill_entry(root, e, seen) for e in raw.get("skills") or []]
    pending = [_check_pending_entry(root, e, seen) for e in raw.get("pending") or []]
    return {"skills": skills, "pending": pending}


def strip_front_matter(text: str) -> str:
    """Drop a leading YAML front-matter block: the skill carries its own."""
    return _FRONT_MATTER_RE.sub("", text, count=1).lstrip("\n")


def _sop_heading_region(text: str, heading: str) -> str:
    """Like extract_heading_region, but fence-aware: a `# comment` line inside a
    ``` block is not a heading (SOPs carry shell scripts; the persona helper
    would cut a section at the first one)."""
    lines = text.splitlines()
    target = heading.strip()
    start = end = None
    level = 0
    in_fence = False
    for i, line in enumerate(lines):
        if line.lstrip().startswith(("```", "~~~")):
            in_fence = not in_fence
            continue
        if in_fence or not line.startswith("#"):
            continue
        if start is None:
            if line.strip() == target:
                start, level = i, _heading_level(line)
        elif _heading_level(line) <= level:
            end = i
            break
    if start is None:
        raise ValueError(f"heading not found: {heading!r}")
    return "\n".join(lines[start:end if end is not None else len(lines)]).strip("\n")


def _frontmatter_text(data: dict) -> str:
    return "---\n" + yaml.safe_dump(data, sort_keys=False, width=10**9, allow_unicode=True) + "---"


def _claude_frontmatter(entry: dict) -> dict:
    return {"name": SOP_SKILL_PREFIX + entry["slug"], "description": entry["description"]}


def _codex_frontmatter(entry: dict) -> dict:
    data = _claude_frontmatter(entry)
    if entry.get("short_description"):
        data["metadata"] = {"short-description": entry["short_description"]}
    return data


