"""T-3339 Phase 1 — persona-orientation renderer.

Reads rulebook/persona-orientation/manifest.yaml + role-deltas.yaml, extracts
named regions from the ratified source files they point at (never fabricated
content), and renders:

  - the Claude base-layer skill (~/.claude/skills/pantheon-persona-orientation/SKILL.md)
  - one role-delta skill per pure-Claude role (~/.claude/skills/pantheon-role-<role>/SKILL.md)

and stamps rulebook/persona-orientation/source-bindings.yaml with the git
provenance (commit, blob, sha256, byte length) of every source file read, so
tools/persona_orientation/check_stale.py can detect drift later.

CLI:
    render.py             extract, render, WRITE artifacts, stamp source-bindings.yaml
    render.py --dry-run   extract, render, print to stdout, write nothing
    render.py --check     extract, render in-memory, diff vs on-disk artifacts;
                           exit 2 on any mismatch, 0 if all match, writes nothing

Idempotent: given unchanged manifest.yaml/role-deltas.yaml and unchanged
source files, two consecutive `render.py` invocations produce byte-identical
artifacts. No timestamps are embedded in generated content; section/role
order follows manifest declaration order (not re-sorted).
"""
from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

import yaml

GENERATED_HEADER = (
    "<!-- GENERATED by tools/persona_orientation/render.py from "
    "rulebook/persona-orientation/manifest.yaml + role-deltas.yaml. "
    "Do not hand-edit; edit the manifest/role-deltas and re-render. -->"
)

# Only these roles get a rendered Claude-side role skill in Phase 1
# (Cairn roles are Phase 5, gated on the T-3333 charter ruling).
CLAUDE_ROLES = {
    "implementer",
    "reviewer",
    "project_orchestrator",
    "orchestrator",
    "research",
    "recovery",
}

BASE_SECTION_TITLES = {
    "p_d_vocabulary": "P/D vocabulary — quick reference",
    "policy_triggers": "Policy trigger cheat-sheet",
    "discovery_checklist": "Session-open discovery checklist",
    "agents_claude_constraints": "AGENTS.md / CLAUDE.md overlay rule",
    "smoke_report_contract": "Smoke / report contract",
    "forbidden_byte_guard": "Forbidden-byte guard",
}


def repo_root() -> Path:
    """tools/persona_orientation/render.py -> repo root (parents[2])."""
    return Path(__file__).resolve().parents[2]


def home_root() -> Path:
    return Path.home()


# ---------------------------------------------------------------------------
# Manifest / role-deltas loading
# ---------------------------------------------------------------------------

def load_manifest(root: Path) -> dict:
    path = root / "rulebook" / "persona-orientation" / "manifest.yaml"
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)


def load_role_deltas(root: Path) -> dict:
    path = root / "rulebook" / "persona-orientation" / "role-deltas.yaml"
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)


# ---------------------------------------------------------------------------
# Git provenance
# ---------------------------------------------------------------------------

def _git(root: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", *args], cwd=root, check=True, capture_output=True, text=True,
    )
    return result.stdout.strip()


def blob_at(root: Path, revision: str, rel_path: str) -> str:
    return _git(root, "rev-parse", f"{revision}:{rel_path}")


def last_commit_touching(root: Path, rel_path: str) -> str:
    """The most recent commit that changed rel_path. Stable across LATER,
    unrelated commits (unlike current HEAD) -- required for idempotency:
    render.py must produce byte-identical output when re-run after an
    unrelated commit lands, as long as this file's own content is
    unchanged. Assumes a clean working tree at rel_path matching HEAD
    (the manual-render workflow renders after a ratified change is
    committed, not against dirty state)."""
    return _git(root, "log", "-1", "--format=%H", "--", rel_path)


# ---------------------------------------------------------------------------
# Source reading (one read per unique path; records a source-binding entry)
# ---------------------------------------------------------------------------

class SourceCache:
    def __init__(self, root: Path):
        self.root = root
        self._text_cache: dict[str, str] = {}
        self.bindings: dict[str, dict[str, Any]] = {}

    def text(self, rel_path: str) -> str:
        if rel_path not in self._text_cache:
            raw = (self.root / rel_path).read_bytes()
            self._text_cache[rel_path] = raw.decode("utf-8")
            source_sha = last_commit_touching(self.root, rel_path)
            self.bindings[rel_path] = {
                "git_sha": source_sha,
                "git_blob": blob_at(self.root, source_sha, rel_path),
                "sha256": hashlib.sha256(raw).hexdigest(),
                "byte_length": len(raw),
            }
        return self._text_cache[rel_path]


# ---------------------------------------------------------------------------
# Markdown heading / paragraph primitives
# ---------------------------------------------------------------------------

def _heading_level(line: str) -> int:
    return len(line) - len(line.lstrip("#"))


def _find_heading_line(lines: list[str], heading: str) -> int:
    target = heading.strip()
    for i, line in enumerate(lines):
        if line.strip() == target:
            return i
    raise ValueError(f"heading not found: {heading!r}")


def _section_end(lines: list[str], start: int) -> int:
    """Index of the next heading at same-or-shallower level than
    lines[start] (which must itself be a heading line), or len(lines)."""
    level = _heading_level(lines[start])
    for i in range(start + 1, len(lines)):
        if lines[i].startswith("#") and _heading_level(lines[i]) <= level:
            return i
    return len(lines)


def _blocks_after(lines: list[str], start_exclusive: int, end: int) -> list[list[str]]:
    """Blank-line-delimited blocks within lines[start_exclusive+1:end]."""
    blocks: list[list[str]] = []
    current: list[str] = []
    for line in lines[start_exclusive + 1:end]:
        if line.strip() == "":
            if current:
                blocks.append(current)
                current = []
        else:
            current.append(line)
    if current:
        blocks.append(current)
    return blocks


_LIST_ITEM_RE = re.compile(r"^\s*(?:[-*]|\d+\.)\s")


def _is_list_block(block: list[str]) -> bool:
    return bool(block) and bool(_LIST_ITEM_RE.match(block[0]))


def _select_block(blocks: list[list[str]], prefix: str | None) -> list[str]:
    """First block, or (if prefix given) the first block whose first line
    starts with prefix, falling back to the first block if none match.

    A ratified source sometimes separates a lead sentence from its bulleted/
    numbered continuation with a blank line (e.g. directives.md:301-305).
    Blank-line-delimited blocking alone would silently drop that
    continuation, so the selected block absorbs any immediately-following
    blocks that are themselves list items -- stopping at the first
    non-list block, so unrelated later paragraphs are never pulled in."""
    if not blocks:
        return []
    if prefix is None:
        index = 0
    else:
        index = next((i for i, b in enumerate(blocks) if b[0].startswith(prefix)), 0)
    selected = list(blocks[index])
    for block in blocks[index + 1:]:
        if not _is_list_block(block):
            break
        selected.append("")
        selected.extend(block)
    return selected


def extract_full_file(text: str) -> str:
    return text.strip("\n")


def extract_heading_region(text: str, heading: str) -> str:
    lines = text.splitlines()
    start = _find_heading_line(lines, heading)
    end = _section_end(lines, start)
    return "\n".join(lines[start:end]).strip("\n")


def extract_heading_region_paragraph(text: str, heading: str, select_prefix: str | None = None) -> str:
    lines = text.splitlines()
    start = _find_heading_line(lines, heading)
    end = _section_end(lines, start)
    block = _select_block(_blocks_after(lines, start, end), select_prefix)
    return "\n".join(block).strip("\n")


def extract_first_line_after_heading(text: str, heading: str) -> str:
    """The single non-blank line immediately following `heading` (used for
    p_d_vocabulary against principles.md, where the body description is
    exactly one hard-line-break-separated line, followed by "**Why:**" with
    no blank line between — a blank-line paragraph split would over-capture)."""
    lines = text.splitlines()
    start = _find_heading_line(lines, heading)
    for line in lines[start + 1:]:
        if line.strip() != "":
            return line.strip()
        break  # heading followed immediately by a blank line: no body line
    return ""


def extract_heading_list(cache: SourceCache, source_specs: list[dict]) -> list[tuple[str, str, str]]:
    """Returns [(id, title, paragraph), ...] across all source_specs, in
    file-then-appearance order.

    If a source spec names `directive_prefix`, the paragraph selected is the
    first blank-line-delimited block whose first line starts with that
    prefix (directives.md's metadata-block-then-directive-text shape).
    Otherwise the single non-blank source line immediately after the
    heading is used (principles.md's shape: heading, one body line, then
    "**Why:**" with no blank line separating them).
    """
    entries: list[tuple[str, str, str]] = []
    for spec in source_specs:
        text = cache.text(spec["path"])
        pattern = re.compile(spec["heading_regex"])
        lines = text.splitlines()
        prefix = spec.get("directive_prefix")
        for i, line in enumerate(lines):
            m = pattern.match(line)
            if not m:
                continue
            entry_id, title = m.group(1), m.group(2)
            if prefix:
                end = _section_end(lines, i)
                block = _select_block(_blocks_after(lines, i, end), prefix)
                paragraph = "\n".join(block).strip("\n")
            else:
                paragraph = extract_first_line_after_heading(text, line)
            entries.append((entry_id, title, paragraph))
    return entries


# ---------------------------------------------------------------------------
# Section / delta rendering
# ---------------------------------------------------------------------------

def render_base_section(cache: SourceCache, section: dict) -> str:
    mode = section["extract"]
    if mode == "inline":
        return section["body"].strip("\n")
    if mode == "heading-list":
        entries = extract_heading_list(cache, section["sources"])
        return "\n".join(f"- **{i} — {t}** — {p}" for i, t, p in entries)
    if mode == "heading-region-paragraph":
        parts = []
        for spec in section["sources"]:
            text = cache.text(spec["path"])
            paragraph = extract_heading_region_paragraph(
                text, spec["heading"], spec.get("select_prefix"),
            )
            parts.append(f"### `{spec['label']}`\n\n{paragraph}\n\nFull: `{spec['path']}`.")
        return "\n\n".join(parts)
    raise ValueError(f"unsupported base_layer extract mode: {mode!r}")


def render_delta_part(cache: SourceCache, part: dict) -> str:
    mode = part["extract"]
    if mode == "inline":
        return part["body"].strip("\n")
    text = cache.text(part["source"])
    if mode == "full-file":
        return extract_full_file(text)
    if mode == "heading-region":
        return extract_heading_region(text, part["heading"])
    raise ValueError(f"unsupported role-delta extract mode: {mode!r}")


def render_delta_section(cache: SourceCache, value) -> str:
    parts = value if isinstance(value, list) else [value]
    return "\n\n".join(render_delta_part(cache, part) for part in parts)


# ---------------------------------------------------------------------------
# Skill assembly
# ---------------------------------------------------------------------------

def render_base_skill(cache: SourceCache, manifest: dict) -> str:
    lines = [
        "---",
        "name: pantheon-persona-orientation",
        "description: Persona-level fleet orientation -- P/D vocabulary, policy-trigger",
        "  cheat sheet, and session-open discovery checklist. Auto-loads on every",
        "  Pantheon persona spawn (user-scope). Rendered from",
        "  rulebook/persona-orientation/manifest.yaml (T-3339); do not hand-edit.",
        "---",
        "",
        GENERATED_HEADER,
        "",
        "# Pantheon persona orientation",
        "",
        "Rendered base layer. Originally hand-authored under T-3301; this file is now",
        "the renderer's output -- see T-3339 for the manifest-driven pipeline that",
        "replaced the hand-authored version. Source of truth for content is",
        "`rulebook/persona-orientation/manifest.yaml` + `role-deltas.yaml`; edit those,",
        "then re-render (`python3 tools/persona_orientation/render.py`).",
        "",
    ]
    for i, section in enumerate(manifest["base_layer"]["sections"], start=1):
        title = BASE_SECTION_TITLES.get(section["id"], section["id"])
        lines.append(f"## {i}. {title}")
        lines.append("")
        lines.append(render_base_section(cache, section))
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def render_role_skill(cache: SourceCache, role: dict, role_deltas: dict) -> str:
    role_id = role["id"]
    deltas_for_role = role_deltas.get("roles", {}).get(role_id, {})
    skill_name = f"pantheon-role-{role_id.replace('_', '-')}"
    lines = [
        "---",
        f"name: {skill_name}",
        f"description: Role-delta orientation for the {role_id} role -- composes on top",
        "  of the pantheon-persona-orientation base layer. Rendered from",
        "  rulebook/persona-orientation/manifest.yaml + role-deltas.yaml (T-3339); do",
        "  not hand-edit.",
        "---",
        "",
        GENERATED_HEADER,
        "",
        f"# Pantheon role orientation -- {role_id}",
        "",
        "Loads alongside `pantheon-persona-orientation` (the base layer) when spawned",
        f"as `{role_id}`. This skill is the role-specific delta only -- it does not",
        "restate the base layer.",
        "",
        "## Tool scope (per manifest -- not yet structurally enforced; Phase 4 per T-3339 plan)",
        "",
        f"- tool_scope: {role.get('tool_scope', [])}",
        f"- forbidden_tools: {role.get('forbidden_tools', [])}",
    ]
    if role.get("activation"):
        lines.append(f"- activation: {role['activation']}")
    lines.append("")
    for delta_id in role["delta_sections"]:
        lines.append(f"## {delta_id.replace('_', ' ')}")
        lines.append("")
        if delta_id in deltas_for_role:
            lines.append(render_delta_section(cache, deltas_for_role[delta_id]))
        else:
            lines.append(
                "(No delta content populated yet -- see "
                "rulebook/persona-orientation/role-deltas.yaml.)"
            )
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


# ---------------------------------------------------------------------------
# Rendering driver
# ---------------------------------------------------------------------------

def render_all(root: Path) -> tuple[dict[str, str], dict[str, dict]]:
    """Returns (artifacts, source_bindings). `artifacts` maps an internal key
    ("base" or "role:<id>") to rendered text; resolve to actual output paths
    via output_paths()."""
    manifest = load_manifest(root)
    role_deltas = load_role_deltas(root)
    cache = SourceCache(root)

    artifacts: dict[str, str] = {"base": render_base_skill(cache, manifest)}
    for role in manifest["roles"]:
        if role["id"] not in CLAUDE_ROLES:
            continue
        artifacts[f"role:{role['id']}"] = render_role_skill(cache, role, role_deltas)

    return artifacts, cache.bindings


def output_paths(home: Path, artifacts: dict[str, str]) -> dict[str, Path]:
    paths: dict[str, Path] = {}
    for key in artifacts:
        if key == "base":
            paths[key] = home / ".claude" / "skills" / "pantheon-persona-orientation" / "SKILL.md"
        else:
            role_id = key.split(":", 1)[1]
            skill_name = f"pantheon-role-{role_id.replace('_', '-')}"
            paths[key] = home / ".claude" / "skills" / skill_name / "SKILL.md"
    return paths


def write_source_bindings(root: Path, bindings: dict[str, dict]) -> None:
    path = root / "rulebook" / "persona-orientation" / "source-bindings.yaml"
    header = (
        "# WRITE-ONLY by tools/persona_orientation/render.py. Do not hand-edit.\n"
        "# Records {source_path: {git_sha, git_blob, sha256, byte_length}} as of\n"
        "# the most recent non-dry-run render. Read by\n"
        "# tools/persona_orientation/check_stale.py to detect drift.\n"
    )
    ordered = {k: bindings[k] for k in sorted(bindings)}
    body = yaml.safe_dump(ordered, sort_keys=True, default_flow_style=False)
    path.write_text(header + body, encoding="utf-8")


def run(root: Path, home: Path, mode: str) -> int:
    artifacts, bindings = render_all(root)
    paths = output_paths(home, artifacts)

    if mode == "dry-run":
        for key, text in artifacts.items():
            print(f"===== {paths[key]} =====")
            print(text)
        return 0

    if mode == "check":
        mismatches = [
            str(paths[key])
            for key, text in artifacts.items()
            if not paths[key].exists() or paths[key].read_text(encoding="utf-8") != text
        ]
        if mismatches:
            print("STALE -- the following artifacts do not match a fresh render:", file=sys.stderr)
            for m in mismatches:
                print(f"  {m}", file=sys.stderr)
            return 2
        print("OK -- all rendered artifacts match on-disk content.")
        return 0

    # default: write
    for key, text in artifacts.items():
        path = paths[key]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    write_source_bindings(root, bindings)
    print(f"Rendered {len(artifacts)} artifact(s); stamped {len(bindings)} source binding(s).")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--dry-run", action="store_true", help="print outputs, write nothing")
    group.add_argument("--check", action="store_true", help="verify on-disk artifacts match a fresh render; exit 2 on mismatch")
    args = parser.parse_args(argv)

    mode = "dry-run" if args.dry_run else "check" if args.check else "write"
    return run(repo_root(), home_root(), mode)


if __name__ == "__main__":
    sys.exit(main())
