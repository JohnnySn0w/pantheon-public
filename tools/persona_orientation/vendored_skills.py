"""T-6116 -- role-gated render of vendored third-party skills into ~/.claude/skills.

Reads tools/persona_orientation/vendored-skills.yaml and renders each entry's source
dir (skills/vendored/<upstream>/<skill>/) as a COPY at ~/.claude/skills/<name>/ for the
Claude harness. Reference files are byte-identical; SKILL.md gets the renderer's
GENERATED marker inserted after its frontmatter (the source is never touched).

Safety properties (supply-chain pilot):
  - role-gated: an entry with `roles:` renders only on a seat holding one of them.
    Unknown seat identity renders NOTHING for such an entry (fail-closed, unlike the
    SOP-skills' fail-open) and prunes nothing (a transient identity failure must not
    flap installed skills). An entry without `roles:` renders on every seat.
  - sources are markdown only: any non-.md file or symlink in a source tree is refused.
  - sha256 bindings (vendored-skill-bindings.yaml) record every source file; an in-scope
    entry whose source differs from its stamp is refused (rc 2), so bytes nobody
    re-stamped in a reviewed PR never reach a seat.
  - only dirs this renderer generated (SKILL.md carries the marker naming the manifest)
    are ever overwritten or pruned; a same-named symlink or hand-written dir is skipped.

Fleet flip: delete (or widen) the `roles:` line of an entry in a reviewed PR.
Rollback: revert the manifest entry and re-render; the generated copy is pruned.
"""
from __future__ import annotations

import hashlib
import os
import pwd
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

import yaml

MANIFEST = "tools/persona_orientation/vendored-skills.yaml"
BINDINGS = "tools/persona_orientation/vendored-skill-bindings.yaml"
VENDORED_ROOT = "skills/vendored"
GENERATED_MARKER = "<!-- GENERATED by tools/persona_orientation/render.py"
OWNER_TAG = "vendored-skills.yaml"  # a generated dir is ours only if its marker line names this
HARNESSES_SUPPORTED = ("claude",)
_SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
_FRONT_MATTER_RE = re.compile(r"\A---\n.*?\n---\n", re.DOTALL)
_ENTRY_KEYS = {"name", "source", "harnesses", "roles"}


def skills_dir(home: Path) -> Path:
    return home / ".claude" / "skills"


# ---------------------------------------------------------------------------
# Manifest
# ---------------------------------------------------------------------------

def load_manifest(root: Path) -> list[dict]:
    path = root / MANIFEST
    if not path.is_file() or not (root / VENDORED_ROOT).is_dir():
        return []  # feature absent (e.g. the public seed excludes skills/vendored/)
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(data, dict) or set(data) - {"skills"}:
        raise ValueError(f"{MANIFEST}: top level must be a mapping with only `skills`")
    skills = data.get("skills") or []
    if not isinstance(skills, list):
        raise ValueError(f"{MANIFEST}: `skills` must be a list")
    seen: set[str] = set()
    return [_check_entry(root, e, seen) for e in skills]


def _check_entry(root: Path, entry: Any, seen: set[str]) -> dict:
    if not isinstance(entry, dict):
        raise ValueError("vendored entry must be a mapping")
    unknown = set(entry) - _ENTRY_KEYS
    if unknown:
        raise ValueError(f"vendored entry has unknown keys {sorted(unknown)}")
    name, source = entry.get("name"), entry.get("source")
    if not isinstance(name, str) or not _SLUG_RE.match(name) or len(name) > 64:
        raise ValueError(f"vendored entry: bad name {name!r}")
    if name in seen:
        raise ValueError(f"{name}: duplicate name")
    seen.add(name)
    if not isinstance(source, str):
        raise ValueError(f"{name}: source must be a string")
    parts = Path(source).parts
    if (
        Path(source).is_absolute()
        or ".." in parts
        or parts[:2] != tuple(VENDORED_ROOT.split("/"))
        or len(parts) < 3
        or parts[-1] != name
    ):
        raise ValueError(f"{name}: source must be {VENDORED_ROOT}/<upstream>/{name} (got {source!r})")
    src = root / source
    if src.is_symlink() or not (src / "SKILL.md").is_file():
        raise ValueError(f"{name}: source dir missing, symlinked, or without SKILL.md")
    if "harnesses" in entry:
        h = entry["harnesses"]
        if not isinstance(h, list) or not h or not set(h) <= set(HARNESSES_SUPPORTED):
            raise ValueError(f"{name}: harnesses must be a non-empty subset of {list(HARNESSES_SUPPORTED)}")
    if "roles" in entry:
        r = entry["roles"]
        if not isinstance(r, list) or not r or not all(isinstance(x, str) and x.strip() for x in r) or len(set(r)) != len(r):
            raise ValueError(f"{name}: roles must be a non-empty list of distinct role ids")
    return entry


def in_scope(entry: dict, seat_roles: frozenset[str] | None) -> bool:
    """No `roles:` -> every seat. With `roles:` -> only a seat that resolved AND holds one (fail-closed)."""
    if "claude" not in (entry.get("harnesses") or HARNESSES_SUPPORTED):
        return False
    wanted = entry.get("roles")
    if wanted is None:
        return True
    return seat_roles is not None and bool(seat_roles & set(wanted))


# ---------------------------------------------------------------------------
# Source reading, hashing, rendering
# ---------------------------------------------------------------------------

def source_files(root: Path, entry: dict) -> dict[str, Path]:
    """rel posix path -> file, for the whole source tree. Refuses symlinks and non-.md files."""
    base = root / entry["source"]
    out: dict[str, Path] = {}
    for dp, dirnames, filenames in os.walk(base, followlinks=False):
        for d in dirnames:
            if (Path(dp) / d).is_symlink():
                raise ValueError(f"{entry['name']}: symlinked dir in source: {Path(dp) / d}")
        for f in filenames:
            p = Path(dp) / f
            if p.is_symlink() or not p.is_file():
                raise ValueError(f"{entry['name']}: symlink or special file in source: {p}")
            if p.suffix != ".md":
                raise ValueError(f"{entry['name']}: non-markdown file in source refused: {p}")
            out[p.relative_to(base).as_posix()] = p
    return dict(sorted(out.items()))


def source_hashes(root: Path, entry: dict) -> dict[str, str]:
    return {rel: hashlib.sha256(p.read_bytes()).hexdigest() for rel, p in source_files(root, entry).items()}


def generated_line(entry: dict) -> str:
    return (
        f"{GENERATED_MARKER} from {MANIFEST} + {entry['source']}/SKILL.md. "
        "Do not hand-edit; edit the source in a reviewed PR and re-stamp. -->"
    )


def render_entry(root: Path, entry: dict) -> dict[str, bytes]:
    """rel path -> bytes. References verbatim; SKILL.md with the marker after its frontmatter."""
    out: dict[str, bytes] = {}
    for rel, p in source_files(root, entry).items():
        data = p.read_bytes()
        if rel == "SKILL.md":
            text = data.decode("utf-8")
            m = _FRONT_MATTER_RE.match(text)
            if not m:
                raise ValueError(f"{entry['name']}: SKILL.md has no frontmatter")
            if not re.search(rf"(?m)^name:\s*{re.escape(entry['name'])}\s*$", m.group(0)):
                raise ValueError(f"{entry['name']}: SKILL.md frontmatter name does not match the entry")
            if GENERATED_MARKER in text:
                raise ValueError(f"{entry['name']}: source already carries a GENERATED marker")
            rest = text[m.end():]
            data = (text[: m.end()] + "\n" + generated_line(entry) + "\n" + ("" if rest.startswith("\n") else "\n") + rest).encode("utf-8")
        out[rel] = data
    return out


# ---------------------------------------------------------------------------
# Bindings
# ---------------------------------------------------------------------------

def compute_bindings(root: Path, entries: list[dict]) -> dict[str, dict]:
    return {e["name"]: {"source": e["source"], "files": source_hashes(root, e)} for e in entries}


def load_bindings(root: Path) -> dict:
    try:
        data = yaml.safe_load((root / BINDINGS).read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError):
        return {}
    return data if isinstance(data, dict) else {}


def binding_problem(root: Path, entry: dict, bindings: dict) -> str | None:
    """None when the source matches its committed stamp; else a human-readable reason."""
    stamped = bindings.get(entry["name"])
    if not isinstance(stamped, dict):
        return f"{entry['name']}: UNSTAMPED (no entry in {BINDINGS})"
    now = source_hashes(root, entry)
    then = stamped.get("files") or {}
    if stamped.get("source") != entry["source"] or now != then:
        changed = sorted(set(now) ^ set(then) | {k for k in now if k in then and now[k] != then[k]})
        return f"{entry['name']}: source differs from its stamp ({', '.join(changed[:5])}); re-stamp in a reviewed PR"
    return None


def write_bindings(root: Path, bindings: dict[str, dict]) -> None:
    header = (
        "# WRITE-ONLY by tools/persona_orientation/render.py. Do not hand-edit.\n"
        "# sha256 of every file under each vendored skill source named in\n"
        "# tools/persona_orientation/vendored-skills.yaml, stamped by a non-dry, stamping render.\n"
        "# render.py refuses an in-scope entry whose source differs from this stamp, and\n"
        "# tools/test_persona_orientation_vendored_skills.py gates the committed pair.\n"
    )
    body = yaml.safe_dump(dict(sorted(bindings.items())), sort_keys=True, default_flow_style=False) if bindings else "{}\n"
    path = root / BINDINGS
    new = header + body
    if path.is_file() and path.read_text(encoding="utf-8") == new:
        return
    path.write_text(new, encoding="utf-8")


# ---------------------------------------------------------------------------
# On-disk state
# ---------------------------------------------------------------------------

def _owned(dest: Path) -> bool:
    """A dir this renderer generated: real dir, real SKILL.md carrying our marker line."""
    skill = dest / "SKILL.md"
    if dest.is_symlink() or not dest.is_dir() or skill.is_symlink() or not skill.is_file():
        return False
    try:
        text = skill.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False
    return any(GENERATED_MARKER in ln and OWNER_TAG in ln for ln in text.splitlines())


def _blocked(dest: Path) -> bool:
    """dest exists and is not ours (symlink, file, hand-written or non-empty foreign dir)."""
    if not dest.exists() and not dest.is_symlink():
        return False
    if _owned(dest):
        return False
    if dest.is_dir() and not dest.is_symlink() and not any(dest.iterdir()):
        return False
    return True


def _existing(dest: Path) -> tuple[dict[str, bytes | None], list[Path]]:
    """(rel -> bytes for regular files; None for a symlink), plus symlinked dirs, under an owned dest."""
    files: dict[str, bytes | None] = {}
    linked_dirs: list[Path] = []
    for dp, dirnames, filenames in os.walk(dest, followlinks=False):
        for d in dirnames:
            if (Path(dp) / d).is_symlink():
                linked_dirs.append(Path(dp) / d)
        for f in filenames:
            p = Path(dp) / f
            files[p.relative_to(dest).as_posix()] = None if p.is_symlink() else p.read_bytes()
    return files, linked_dirs


def _stale(dest: Path, expected: dict[str, bytes]) -> list[str]:
    if not dest.exists():
        return [f"{dest} (missing)"]
    have, linked_dirs = _existing(dest)
    out = [f"{dest / rel} ({'missing' if rel not in have else 'differs'})"
           for rel, data in expected.items() if have.get(rel) != data]
    out += [f"{dest / rel} (extra)" for rel in have if rel not in expected]
    out += [f"{p} (symlinked dir)" for p in linked_dirs]
    return out


def find_orphans(home: Path, active: set[str]) -> list[Path]:
    base = skills_dir(home)
    if not base.is_dir():
        return []
    return [d for d in sorted(base.iterdir()) if d.name not in active and _owned(d)]


def prune(dest: Path) -> None:
    """Remove our generated copy: .md files and symlinks, then the emptied dirs."""
    for dp, dirnames, filenames in os.walk(dest, topdown=False, followlinks=False):
        for f in filenames:
            p = Path(dp) / f
            if p.is_symlink() or p.suffix == ".md":
                p.unlink()
        for d in dirnames:
            p = Path(dp) / d
            if p.is_symlink():
                p.unlink()
            else:
                try:
                    p.rmdir()
                except OSError:
                    pass
    try:
        dest.rmdir()
    except OSError:
        pass


def _write_entry(dest: Path, expected: dict[str, bytes]) -> None:
    if dest.exists():
        have, linked_dirs = _existing(dest)
        for p in linked_dirs:
            p.unlink()
        for rel in have:
            if rel not in expected or have[rel] is None:
                (dest / rel).unlink()
    dest.mkdir(parents=True, exist_ok=True)
    for rel in sorted(expected, key=lambda r: (r != "SKILL.md", r)):  # SKILL.md first: ownership marker lands first
        p = dest / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(expected[rel])



# ---------------------------------------------------------------------------
# Real-home write guard (T-6116 deviation: a branch/test run wrote the live ~/.claude/skills)
# ---------------------------------------------------------------------------

class UnsafeWriteTarget(RuntimeError):
    """Refusal to write/prune vendored copies into the real account home from a test or a non-main checkout."""


def _real_home() -> Path:
    """The OS account's home from the passwd entry (NOT $HOME, which a test can repoint)."""
    return Path(pwd.getpwuid(os.getuid()).pw_dir).resolve()


def _current_branch(root: Path) -> str:
    try:
        r = subprocess.run(["git", "-C", str(root), "branch", "--show-current"],
                           capture_output=True, text=True, timeout=10)
        return r.stdout.strip() if r.returncode == 0 else ""
    except (OSError, subprocess.SubprocessError):
        return ""


def _under(path: Path, base: Path) -> bool:
    return path == base or base in path.parents


def assert_safe_write_target(root: Path, home: Path) -> None:
    """Fail closed (raise) before any write or prune into a LIVE home.

    A live home is the passwd-entry home or any /home/* path. Writing there is allowed ONLY when
    PYTEST_CURRENT_TEST is unset AND the repo root's branch is positively `main` (the seat's own
    checkout, which is what inbox_consumer runs from). An empty branch (detached HEAD, git error,
    not a repo) or any other branch refuses. Targets elsewhere (tmp dirs) are unrestricted."""
    target = home.resolve()
    live = _under(target, _real_home()) or str(target).startswith("/home/")
    if not live:
        return
    if os.environ.get("PYTEST_CURRENT_TEST"):
        raise UnsafeWriteTarget(f"refusing to write vendored skills under {target} while running under pytest")
    branch = _current_branch(root)
    if branch != "main":
        raise UnsafeWriteTarget(
            f"refusing to write vendored skills into {target} from {root} (branch {branch or '<detached/unknown>'!r}, "
            "not main); use --check/--dry-run, or render from the main checkout after merge")


# ---------------------------------------------------------------------------
# Entry point (called by render.run)
# ---------------------------------------------------------------------------

def run_vendored(root: Path, home: Path, mode: str, seat_roles: frozenset[str] | None, stamp: bool = True) -> int:
    """0 = ok, 2 = drift / missing / orphan / tamper. mode: dry-run | check | write."""
    entries = load_manifest(root)
    if not entries:
        return 0
    gated = [e for e in entries if e.get("roles") and "claude" in (e.get("harnesses") or HARNESSES_SUPPORTED)]
    if seat_roles is None and gated:
        print("NOTE -- seat identity not resolved: vendored skills with `roles:` are NOT rendered and nothing is pruned (fail-closed).")
    scoped = [e for e in entries if in_scope(e, seat_roles)]

    if mode == "write" and stamp:
        write_bindings(root, compute_bindings(root, entries))
    bindings = load_bindings(root)

    problems: list[str] = []
    todo: list[tuple[dict, Path, dict[str, bytes]]] = []
    blocked: list[Path] = []
    for e in scoped:
        bad = binding_problem(root, e, bindings)
        if bad:
            problems.append(f"TAMPER -- {bad}")
            continue
        dest = skills_dir(home) / e["name"]
        if _blocked(dest):
            blocked.append(dest)
            continue
        todo.append((e, dest, render_entry(root, e)))
    for dest in blocked:
        print(f"NOTE -- {dest} exists and is not a vendored-skills render (symlink or hand-written): skipped, never pruned.")

    orphans = find_orphans(home, {e["name"] for e in scoped}) if seat_roles is not None else []
    # an entry refused for TAMPER keeps its installed copy out of the orphan set
    refused = {e["name"] for e in scoped} - {e["name"] for e, _, _ in todo}
    orphans = [o for o in orphans if o.name not in refused]

    if mode == "dry-run":
        for e, dest, files in todo:
            print(f"===== {dest} ({len(files)} file(s)) =====")
            for rel in files:
                print(f"  {rel}")
        for o in orphans:
            print(f"(would prune vendored orphan {o})")
        for p in problems:
            print(p)
        return 0

    stale = [s for _, dest, files in todo for s in _stale(dest, files)]
    if mode == "check":
        for p in problems:
            print(p, file=sys.stderr)
        if stale:
            print("STALE -- vendored-skill copies missing or not matching a fresh render:", file=sys.stderr)
            for s in stale:
                print(f"  {s}", file=sys.stderr)
        if orphans:
            print("ORPHAN -- generated vendored-skill dirs this seat no longer qualifies for "
                  "(render.py without --check prunes them):", file=sys.stderr)
            for o in orphans:
                print(f"  {o}", file=sys.stderr)
        if problems or stale or orphans:
            return 2
        print("OK -- all vendored-skill copies match a fresh render.")
        return 0

    for p in problems:
        print(p, file=sys.stderr)
    if todo or orphans:
        assert_safe_write_target(root, home)  # raises before any write or prune
    for e, dest, files in todo:
        _write_entry(dest, files)
    for o in orphans:
        prune(o)
    print(f"Rendered {len(todo)} vendored skill(s); pruned {len(orphans)} orphan(s); "
          f"{len(entries) - len(scoped)} role-excluded for this seat; {len(problems)} refused.")
    return 2 if problems else 0
