#!/usr/bin/env python3
"""ORG-103 L5 (T-5305): pin codex per app-server seat and gate every bump on the schema.

The app-server protocol is [experimental], so the delivery client (tools/codex_delivery.py)
is only trusted against a codex version whose generated JSON schema it has been checked
against. Three pieces:

  harness/codex/appserver_seats.json          per-seat runtime binding, incl. codex_version
  harness/codex/schema/codex-<ver>/           `codex app-server generate-json-schema` output
                                              for that version (the bundled
                                              codex_app_server_protocol.schemas.json) + VERSION
  this module                                 the contract: every method, notification and
                                              server request the client uses must exist in
                                              the snapshot, the payloads the client really
                                              builds must validate against their params
                                              schema, the refusals it sends must validate
                                              against their response schema, and every field
                                              and enum value it reads must exist.

tools/test_codex_schema_contract.py runs the contract for every pinned version in CI, so a
pin bump without a regenerated snapshot that passes fails CI. When the pinned codex is on
the machine, the test also regenerates the schema and requires it byte-identical to the
snapshot (codex 0.147.0 output is deterministic).

CLI
  codex_schema_contract.py check [--version V]       contract against the snapshot(s)
  codex_schema_contract.py regen --codex-bin BIN     write the snapshot for BIN's version
  codex_schema_contract.py installed --seat S        exit 0 iff S's codex_bin matches its pin
Stdlib only.
"""
from __future__ import annotations

import argparse
import json
import pwd
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any, Optional

REPO = Path(__file__).resolve().parent.parent
BINDINGS = REPO / "harness" / "codex" / "appserver_seats.json"
SCHEMA_ROOT = REPO / "harness" / "codex" / "schema"
BUNDLE = "codex_app_server_protocol.schemas.json"
VERSION_RE = re.compile(r"codex-cli\s+(\d+\.\d+\.\d+\S*)")
INSTANCE_ROOT_CWD = "@instance-root"

if __package__ == "tools":
    from tools import codex_delivery as cd
else:
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import codex_delivery as cd  # noqa: E402


# ------------------------------------------------------------------ bindings / versions
def load_bindings(path: Path = BINDINGS) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))["seats"]


def resolve_binding_cwd(binding: dict, *, instance_root: Path = REPO) -> str:
    """Resolve the active-checkout sentinel while rejecting ambiguous relatives."""
    raw = binding.get("cwd")
    if raw == INSTANCE_ROOT_CWD:
        return str(instance_root.resolve())
    if not isinstance(raw, str) or not Path(raw).is_absolute():
        raise ValueError(
            f"binding cwd must be an absolute path or {INSTANCE_ROOT_CWD!r}, got {raw!r}"
        )
    return raw


def seat_for_account(account: Optional[str] = None, path: Path = BINDINGS) -> Optional[tuple]:
    account = account or pwd.getpwuid(__import__("os").getuid()).pw_name
    for name, b in load_bindings(path).items():
        if b.get("account") == account:
            return name, b
    return None


def codex_version(codex_bin: str, run=subprocess.run) -> Optional[str]:
    try:
        out = run([codex_bin, "--version"], capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return None
    m = VERSION_RE.search((out.stdout or "") + (out.stderr or ""))
    return m.group(1) if m else None


def snapshot_dir(version: str) -> Path:
    return SCHEMA_ROOT / f"codex-{version}"


def load_snapshot(version: str) -> dict:
    d = snapshot_dir(version)
    recorded = (d / "VERSION").read_text(encoding="utf-8").strip()
    if recorded != version:
        raise ValueError(f"{d}/VERSION says {recorded!r}, expected {version!r}")
    return json.loads((d / BUNDLE).read_text(encoding="utf-8"))


def regen(codex_bin: str, out_root: Path = SCHEMA_ROOT, run=subprocess.run) -> Path:
    """Write <out_root>/codex-<ver>/ from `codex_bin`. The version is read from the binary
    itself, so a snapshot can never be filed under a version it was not generated by."""
    ver = codex_version(codex_bin, run=run)
    if not ver:
        raise RuntimeError(f"cannot read a version from {codex_bin} --version")
    with tempfile.TemporaryDirectory() as tmp:
        r = run([codex_bin, "app-server", "generate-json-schema", "--out", tmp],
                capture_output=True, text=True, timeout=120)
        if r.returncode != 0:
            raise RuntimeError(f"generate-json-schema failed rc={r.returncode}: {r.stderr[-300:]}")
        dest = out_root / f"codex-{ver}"
        dest.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(Path(tmp) / BUNDLE, dest / BUNDLE)
        (dest / "VERSION").write_text(ver + "\n", encoding="utf-8")
    return dest


# ------------------------------------------------------------------ mini JSON-schema
class Schema:
    """Just enough draft-07 for the codex bundle: $ref (JSON pointer), allOf/anyOf/oneOf,
    enum/const, type, properties/required/additionalProperties, items. `format` is ignored.
    oneOf is checked as "at least one" (codex's tagged unions do not overlap in practice,
    and a stricter reading would only add false failures)."""

    def __init__(self, doc: dict):
        self.doc = doc

    def resolve(self, node: Any) -> Any:
        seen = 0
        while isinstance(node, dict) and "$ref" in node:
            ref = node["$ref"]
            if not ref.startswith("#/"):
                raise ValueError(f"external $ref {ref}")
            node = self.doc
            for part in ref[2:].split("/"):
                node = node[part]
            seen += 1
            if seen > 64:
                raise ValueError("$ref loop")
        return node

    def errors(self, value: Any, node: Any, path: str = "$") -> list[str]:
        node = self.resolve(node)
        if node is True or node == {}:
            return []
        if node is False:
            return [f"{path}: schema false"]
        errs: list[str] = []
        for sub in node.get("allOf") or []:
            errs += self.errors(value, sub, path)
        for key in ("anyOf", "oneOf"):
            if key in node:
                branches = [self.errors(value, sub, path) for sub in node[key]]
                if all(branches):
                    best = min(branches, key=len)
                    errs.append(f"{path}: matches no {key} branch (closest: {best[:2]})")
        if "enum" in node and value not in node["enum"]:
            errs.append(f"{path}: {value!r} not in {node['enum'][:8]}")
        if "const" in node and value != node["const"]:
            errs.append(f"{path}: {value!r} != const {node['const']!r}")
        t = node.get("type")
        if t is not None:
            types = t if isinstance(t, list) else [t]
            if not any(_is_type(value, x) for x in types):
                return errs + [f"{path}: {type(value).__name__} is not {types}"]
        if isinstance(value, dict) and ("properties" in node or "required" in node
                                        or "additionalProperties" in node):
            props = node.get("properties") or {}
            for req in node.get("required") or []:
                if req not in value:
                    errs.append(f"{path}: missing required {req!r}")
            for k, v in value.items():
                if k in props:
                    errs += self.errors(v, props[k], f"{path}.{k}")
                elif node.get("additionalProperties") is False:
                    errs.append(f"{path}: unexpected property {k!r}")
                elif isinstance(node.get("additionalProperties"), dict):
                    errs += self.errors(v, node["additionalProperties"], f"{path}.{k}")
        if isinstance(value, list) and "items" in node:
            for i, v in enumerate(value):
                errs += self.errors(v, node["items"], f"{path}[{i}]")
        return errs

    def branches(self, node: Any) -> list[dict]:
        """Every object-ish alternative reachable through refs and combinators."""
        node = self.resolve(node)
        if not isinstance(node, dict):
            return []
        out = [node]
        for key in ("allOf", "anyOf", "oneOf"):
            for sub in node.get(key) or []:
                out += self.branches(sub)
        return out

    def has_path(self, node: Any, path: list[str]) -> bool:
        if not path:
            return True
        for br in self.branches(node):
            props = br.get("properties") or {}
            if path[0] in props and self.has_path(props[path[0]], path[1:]):
                return True
            if path[0] == "[]" and "items" in br and self.has_path(br["items"], path[1:]):
                return True
        return False

    def enum_values(self, node: Any) -> set:
        vals: set = set()
        for br in self.branches(node):
            for v in br.get("enum") or []:
                vals.add(v)
            if "const" in br:
                vals.add(br["const"])
        return vals


def _is_type(v: Any, t: str) -> bool:
    return {"object": isinstance(v, dict), "array": isinstance(v, list),
            "string": isinstance(v, str), "boolean": isinstance(v, bool),
            "null": v is None,
            "integer": isinstance(v, int) and not isinstance(v, bool),
            "number": isinstance(v, (int, float)) and not isinstance(v, bool)}.get(t, True)


# ------------------------------------------------------------------ the contract
THREAD = "01a138a3-9e7f-7b22-890b-6b4e1359084b"

# Fields the client READS from responses (method -> paths into the result).
RESULT_READS = {
    "thread/resume": [["thread"], ["thread", "status"], ["thread", "turns"], ["sandbox"],
                      ["approvalPolicy"], ["model"], ["cwd"]],
    "turn/start": [["turn", "id"]],
    "turn/steer": [["turnId"]],
    "thread/read": [["thread", "turns"], ["thread", "turns", "[]", "items"],
                    ["thread", "turns", "[]", "status"]],
    "thread/loaded/list": [["data"]],
    "account/read": [["account"]],
}
# Notifications the client handles -> params paths it reads.
NOTIFICATIONS = {
    "turn/started": [["threadId"], ["turn", "id"]],
    "turn/completed": [["threadId"], ["turn", "id"], ["turn", "status"], ["turn", "items"],
                       ["turn", "error"]],
    "item/started": [["threadId"], ["turnId"], ["item"]],
    "item/completed": [["threadId"], ["turnId"], ["item"]],
    "thread/status/changed": [["threadId"], ["status"]],
    "thread/compacted": [["threadId"], ["turnId"]],
    "error": [["error"], ["willRetry"], ["threadId"], ["turnId"]],
}
# Enum values the client compares against: (definition path, values).
ENUMS = [
    ("v2/TurnStatus", {"completed", "inProgress", "interrupted", "failed"}),
    ("v2/McpToolCallStatus", {"completed"}),        # T-5413 receipt
]
THREAD_STATUS_TYPES = {"active", "idle", "notLoaded", "systemError"}
ITEM_TYPES = {"userMessage", "agentMessage", "contextCompaction", "mcpToolCall"}
# T-5413: the operator receipt (codex_delivery.ack_receipt) reads these on mcpToolCall.
MCP_TOOL_CALL_FIELDS = ("server", "tool", "status", "arguments", "error")
ERROR_INFO = {"unauthorized"}
# Methods the ticket names that the client may grow into (presence only).
PRESENCE_ONLY = ["thread/start", "account/rateLimits/read"]


def _methods(s: Schema, union: str) -> dict:
    out = {}
    for v in s.resolve(s.doc["definitions"][union]).get("oneOf") or []:
        props = v.get("properties") or {}
        m = (props.get("method") or {}).get("enum")
        if m:
            out[m[0]] = props.get("params")
    return out


def _response_for(s: Schema, params_node) -> Optional[Any]:
    ref = (params_node or {}).get("$ref", "")
    if not ref.endswith("Params"):
        return None
    candidate = ref[: -len("Params")] + "Response"
    try:
        return s.resolve({"$ref": candidate})
    except KeyError:
        return None


def client_payloads(policies: list) -> dict:
    """The params the client really sends, built by codex_delivery itself."""
    out: dict[str, list] = {"initialize": [], "thread/resume": [], "turn/start": [],
                            "turn/steer": [], "turn/interrupt": [], "thread/read": [],
                            "thread/loaded/list": [], "account/read": []}
    client = cd.CodexDeliveryClient.__new__(cd.CodexDeliveryClient)
    inp = cd.CodexDeliveryClient._input(client, cd.format_input("hello", "dm-0001", "operator_dm"))
    out["initialize"].append({"clientInfo": {"name": "pantheon_codex_delivery",
                                             "title": "Pantheon codex delivery", "version": "0.1"}})
    for pol in policies:
        out["thread/resume"].append(pol.resume_params(THREAD))
        out["turn/start"].append(dict({"threadId": THREAD, "input": inp}, **pol.turn_params()))
    out["turn/steer"].append({"threadId": THREAD, "expectedTurnId": "t1", "input": inp})
    out["turn/interrupt"].append({"threadId": THREAD, "turnId": "t1"})
    out["thread/read"].append({"threadId": THREAD, "includeTurns": True})
    out["thread/loaded/list"].append({})
    out["account/read"].append({})
    return out


def contract_policies(bindings: dict) -> list:
    pols = []
    for b in bindings.values():
        pols.append(cd.SeatPolicy(b["sandbox"], b["approval_policy"], b.get("model"), b.get("cwd"),
                                  bool(b.get("network_access")), tuple(b.get("writable_roots") or ())))
    # The shapes a narrower seat would send, so a workspace-write seat (Watchman, specialist)
    # is covered before it exists.
    pols.append(cd.SeatPolicy("workspace-write", "never", "m", "/home/x", False, ("/home/x/w",)))
    pols.append(cd.SeatPolicy("read-only", "on-request", "m", "/home/x"))
    return pols


def check(doc: dict, bindings: Optional[dict] = None) -> list[str]:
    """Every contract failure for this schema bundle (empty = passes)."""
    s = Schema(doc)
    fails: list[str] = []
    creq, notes = _methods(s, "ClientRequest"), _methods(s, "ServerNotification")
    sreq, cnote = _methods(s, "ServerRequest"), _methods(s, "ClientNotification")
    if "initialized" not in cnote:
        fails.append("ClientNotification: 'initialized' missing")

    payloads = client_payloads(contract_policies(bindings if bindings is not None else load_bindings()))
    for method, examples in payloads.items():
        if method not in creq:
            fails.append(f"ClientRequest: {method!r} missing")
            continue
        for ex in examples:
            for e in s.errors(ex, creq[method] or {}):
                fails.append(f"{method} params: {e}")
    for method in PRESENCE_ONLY:
        if method not in creq:
            fails.append(f"ClientRequest: {method!r} missing")
    for method, paths in RESULT_READS.items():
        resp = _response_for(s, creq.get(method))
        if resp is None:
            fails.append(f"{method}: no response schema")
            continue
        for p in paths:
            if not s.has_path(resp, p):
                fails.append(f"{method} result: no field {'.'.join(p)}")

    for method, paths in NOTIFICATIONS.items():
        if method not in notes:
            fails.append(f"ServerNotification: {method!r} missing")
            continue
        for p in paths:
            if not s.has_path(notes[method], p):
                fails.append(f"{method} params: no field {'.'.join(p)}")

    for method, refusal in cd.APPROVAL_REFUSALS.items():
        if method not in sreq:
            fails.append(f"ServerRequest: {method!r} missing (the client still answers it)")
            continue
        resp = _response_for(s, sreq[method])
        if resp is None:
            fails.append(f"{method}: no response schema for the refusal")
            continue
        for e in s.errors(refusal, resp):
            fails.append(f"{method} refusal: {e}")
    for method in sreq:
        if "Approval" in method or "elicitation" in method or "requestUserInput" in method:
            if method not in cd.APPROVAL_REFUSALS:
                fails.append(f"ServerRequest: {method!r} is new and has no deny-by-default answer")

    defs = doc["definitions"]
    for dpath, want in ENUMS:
        node: Any = defs
        for part in dpath.split("/"):
            node = node.get(part, {}) if isinstance(node, dict) else {}
        missing = want - s.enum_values(node)
        if missing:
            fails.append(f"{dpath}: missing values {sorted(missing)}")
    status_types = set()
    for br in s.branches({"$ref": "#/definitions/v2/ThreadStatus"}):
        status_types |= s.enum_values((br.get("properties") or {}).get("type", {}))
    if THREAD_STATUS_TYPES - status_types:
        fails.append(f"v2/ThreadStatus: missing types {sorted(THREAD_STATUS_TYPES - status_types)}")
    item_types = set()
    for br in s.branches({"$ref": "#/definitions/v2/ThreadItem"}):
        item_types |= s.enum_values((br.get("properties") or {}).get("type", {}))
    if ITEM_TYPES - item_types:
        fails.append(f"v2/ThreadItem: missing types {sorted(ITEM_TYPES - item_types)}")
    if not any(s.has_path(br, ["content", "[]", "text"])
               for br in s.branches({"$ref": "#/definitions/v2/ThreadItem"})
               if "userMessage" in s.enum_values((br.get("properties") or {}).get("type", {}))):
        fails.append("v2/ThreadItem userMessage: no content[].text (the delivery-id tag lives there)")
    mcp = [br for br in s.branches({"$ref": "#/definitions/v2/ThreadItem"})
           if "mcpToolCall" in s.enum_values((br.get("properties") or {}).get("type", {}))]
    missing = [f for f in MCP_TOOL_CALL_FIELDS
               if not any(f in (br.get("properties") or {}) for br in mcp)]
    if missing:
        fails.append(f"v2/ThreadItem mcpToolCall: missing {missing} (the T-5413 receipt)")
    if ERROR_INFO - s.enum_values({"$ref": "#/definitions/v2/CodexErrorInfo"}):
        fails.append("v2/CodexErrorInfo: 'unauthorized' missing (auth-expiry detection)")
    return fails


def check_pins(bindings: dict, root: Optional[Path] = None) -> dict:
    """{version: [failures]} for every pinned version. A pin with no snapshot, or a
    snapshot whose VERSION disagrees, is a failure: that is the bump gate."""
    global SCHEMA_ROOT
    out = {}
    saved = SCHEMA_ROOT
    if root is not None:
        SCHEMA_ROOT = root
    try:
        for v in sorted({b["codex_version"] for b in bindings.values()}):
            try:
                doc = load_snapshot(v)
            except (OSError, ValueError) as exc:
                out[v] = [f"no usable snapshot for pinned codex {v}: {exc}. Run "
                          f"`tools/codex_schema_contract.py regen --codex-bin <codex {v}>`."]
                continue
            out[v] = check(doc, bindings)
    finally:
        SCHEMA_ROOT = saved
    return out


def check_installed(binding: dict, run=subprocess.run) -> Optional[str]:
    """None when the seat's codex_bin reports its pinned version, else why not."""
    have = codex_version(binding["codex_bin"], run=run)
    if have != binding["codex_version"]:
        return (f"{binding['codex_bin']} reports {have!r}; the seat binding pins "
                f"{binding['codex_version']!r} (harness/codex/appserver_seats.json)")
    return None


# ------------------------------------------------------------------ CLI
def _cli(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("check")
    c.add_argument("--version", action="append")
    r = sub.add_parser("regen")
    r.add_argument("--codex-bin", required=True)
    i = sub.add_parser("installed")
    i.add_argument("--seat", required=True)
    a = ap.parse_args(argv)

    if a.cmd == "regen":
        dest = regen(a.codex_bin)
        fails = check(load_snapshot(dest.name[len("codex-"):]))
        print(f"wrote {dest}; contract: {'PASS' if not fails else 'FAIL'}")
        for f in fails:
            print("  " + f)
        return 0 if not fails else 1
    bindings = load_bindings()
    if a.cmd == "installed":
        b = bindings[a.seat]
        have = codex_version(b["codex_bin"])
        print(json.dumps({"seat": a.seat, "pinned": b["codex_version"], "installed": have}))
        return 0 if have == b["codex_version"] else 1
    if a.version:
        bindings = {f"_{v}": dict(next(iter(bindings.values())), codex_version=v)
                    for v in a.version}
    rc = 0
    for v, fails in check_pins(bindings).items():
        print(f"codex {v}: {'PASS' if not fails else 'FAIL'}")
        for f in fails:
            print("  " + f)
        rc |= bool(fails)
    return rc


if __name__ == "__main__":
    sys.exit(_cli())
