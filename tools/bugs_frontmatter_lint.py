#!/usr/bin/env python3
"""bugs_frontmatter_lint — enforce the bugs/ YAML frontmatter contract.

Closes the CLASS behind T-1772 and T-1912: `bugs/README.md`'s Auto-index is
generated by `spine_index_groom.bugs_handler`, which reads `symptom` / `domain`
from each file's frontmatter and falls back to an em-dash when a key is absent.
A bug file added without frontmatter therefore lands in the catalog but renders
as a placeholder row — invisible to the symptom-grep discovery surface
`bugs/README.md` calls load-bearing. T-1772 backfilled 9 such files by hand;
by T-1912 the count had regrown to 15 of 74 (~20% of the catalog). Manual
backfill fixes the instances; this lint closes the class.

Contract (documented in `bugs/README.md` § File structure) — every `bugs/*.md`
except `README.md` must open with YAML frontmatter carrying all three of:

    symptom:  one-liner of what you're seeing
    fix:      one-liner of what to do
    domain:   comma-separated tags ("systemd", "vitest", "bun", ...)

A key is a VIOLATION when it is absent, empty, or whitespace-only. `fix` is
enforced even though the current index renders only `symptom` + `domain`: the
written contract requires all three, and every conforming file already carries
it. (The README-vs-handler rendering gap is tracked separately and is not this
lint's business.)

Parsing deliberately IMPORTS `_parse_frontmatter` from `spine_index_groom`
rather than reimplementing it. A second parser could drift from the generator's,
producing the worst failure mode available here: lint green while the index
still renders dashes. One parser means "lint passes" and "index clean" cannot
disagree.

NOT enforced — no-literal-pipe. An unescaped `|` in a value splits the markdown
table cell and structurally breaks the row, but 3 rows in the live tree already
carry one (plus 2 more under `knowledge/episodic/`), so enforcing it here would
be born-red. That is a generator-side escaping defect (the fix belongs at the
row-emit site, covering every handler), tracked separately — deliberately out of
scope rather than silently tolerated.

Report-only / read-only: parses committed markdown and authors nothing (no
commits, no subprocess), so it sits outside the auto-commit contract — same
exemption class as the other tools/ lints.

Usage:
    python3 tools/bugs_frontmatter_lint.py           # scan bugs/, exit 1 on violations
    python3 tools/bugs_frontmatter_lint.py --quiet   # exit code only
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from tools.spine_index_groom import _parse_frontmatter  # noqa: E402

#: Keys the bugs/README.md File-structure contract requires on every entry.
REQUIRED_KEYS = ("symptom", "fix", "domain")


def scan(bugs_dir: Path) -> list[tuple[str, list[str]]]:
    """Return [(filename, [missing-or-empty keys]), ...] sorted by filename.

    A file with no frontmatter at all reports every required key as missing —
    that is the dominant real shape (T-1912: 15 files with none, 0 partial).
    """
    findings: list[tuple[str, list[str]]] = []
    for md in sorted(bugs_dir.glob("*.md")):
        if md.name == "README.md":
            continue
        fm = _parse_frontmatter(md)
        bad = [k for k in REQUIRED_KEYS if not fm.get(k, "").strip()]
        if bad:
            findings.append((md.name, bad))
    return findings


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Enforce the bugs/ frontmatter contract (symptom/fix/domain)."
    )
    ap.add_argument(
        "--bugs-dir",
        type=Path,
        default=REPO_ROOT / "bugs",
        help="directory to scan (default: <repo>/bugs)",
    )
    ap.add_argument("--quiet", action="store_true", help="exit code only, no output")
    args = ap.parse_args(argv)

    if not args.bugs_dir.is_dir():
        print(f"[bugs_frontmatter_lint] ERROR: not a directory: {args.bugs_dir}", file=sys.stderr)
        return 2

    findings = scan(args.bugs_dir)

    if args.quiet:
        return 1 if findings else 0

    if not findings:
        total = len([p for p in args.bugs_dir.glob("*.md") if p.name != "README.md"])
        print(f"[bugs_frontmatter_lint] clean — {total} file(s) carry symptom/fix/domain")
        return 0

    print(
        f"[bugs_frontmatter_lint] {len(findings)} file(s) violate the frontmatter "
        f"contract documented in bugs/README.md § File structure:\n"
    )
    for name, bad in findings:
        print(f"  {name}\n      missing/empty: {', '.join(bad)}")
    print(
        "\nEvery bugs/*.md must open with YAML frontmatter:\n"
        '  ---\n  symptom: "one-liner of what you\'re seeing"\n'
        '  fix: "one-liner of what to do"\n  domain: systemd, vitest, ...\n  ---\n'
        "Without it the file renders as a placeholder row in bugs/README.md's\n"
        "Auto-index and is invisible to symptom-grep discovery."
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
